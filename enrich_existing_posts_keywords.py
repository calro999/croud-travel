count = 0
for f in os.listdir(POSTS_DIR):
    if not f.endswith(".json"):
        continue
    fpath = os.path.join(POSTS_DIR, f)
    with open(fpath, "r", encoding="utf-8") as fp:
        try:
            pdata = json.load(fp)
        except Exception:
            continue
    
    text_to_search = (pdata.get("id", "") + " " + 
                      pdata.get("hotel_name", "") + " " + 
                      pdata.get("title", "") + " " + 
                      pdata.get("area", "") + " " + 
                      pdata.get("prefecture", "")).lower()
    
    current_keys = pdata.get("keywords", [])
    modified = False
    
    for m in mappings:
        if any(target.lower() in text_to_search for target in m["match"]):
            for kw in m["keywords"]:
                if kw not in current_keys:
                    current_keys.append(kw)
                    modified = True
                    
    if modified:
        pdata["keywords"] = current_keys
        with open(fpath, "w", encoding="utf-8") as fp:
            json.dump(pdata, fp, ensure_ascii=False, indent=2)
        count += 1

print(f"Updated keywords for {count} hotel/feature posts.")
