def apply_lsi_expansion():
    for filename, info in LSI_MAP.items():
        filepath = os.path.join(POSTS_DIR, filename)
        if not os.path.exists(filepath):
            print(f"⚠️ 未検出: {filename}")
            continue
        with open(filepath, "r", encoding="utf-8") as f:
            data = json.load(f)
        
        # 1. keywords 配列の追加・拡張
        existing_kw = data.get("keywords", [])
        new_kw = list(dict.fromkeys(existing_kw + info["keywords"]))
        data["keywords"] = new_kw
        
        # 2. FAQの追加補強
        faq_item = info.get("extra_faq")
        if faq_item:
            faq_html = f"""
  <div class="p-5 rounded-2xl bg-white border border-stone-200 shadow-sm space-y-2">
    <h4 class="text-sm font-bold text-stone-900 flex items-center gap-2"><span class="px-2 py-0.5 bg-amber-500 text-white text-xs font-black rounded-md">Q</span>{faq_item['q']}</h4>
    <p class="text-xs text-stone-700 leading-relaxed pl-6 border-l-2 border-amber-200"><span class="font-bold text-amber-600">A.</span> {faq_item['a']}</p>
  </div>
"""
            if "review" in data:
                # FAQタグの直前または末尾に挿入
                if "💡 よくある質問（FAQ）" in data["review"]:
                    data["review"] = data["review"].replace('<div class="space-y-4 my-6">', '<div class="space-y-4 my-6">' + faq_html)
                else:
                    data["review"] += f"\n<h2 class=\"text-xl font-bold text-stone-900 border-b-2 border-amber-500 pb-2 my-6\">💡 よくある質問・よく調べられる周辺情報</h2>\n<div class=\"space-y-4 my-6\">{faq_html}</div>"

        with open(filepath, "w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False, indent=2)
        print(f"✅ 検索窓口（LSIキーワード・FAQ）拡張完了: {filename}")

if __name__ == "__main__":
    apply_lsi_expansion()
