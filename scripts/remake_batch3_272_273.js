const fs = require('fs');
const path = require('path');
const { renderArticle } = require('./remake_helper');

const rawAll = JSON.parse(fs.readFileSync(path.join(__dirname, 'remake_266_275_live_data.json'), 'utf8'));
const POSTS_DIR = path.join(__dirname, '..', 'src', 'data', 'posts');
const ROOT_DIR = path.join(__dirname, '..');

function saveBoth(noteNum, slug, config) {
  const { postData, noteMarkdown } = renderArticle({
    noteNum,
    slug,
    rawData: rawAll[String(noteNum)],
    ...config
  });

  const jsonPath = path.join(POSTS_DIR, `${slug}.json`);
  fs.writeFileSync(jsonPath, JSON.stringify(postData, null, 2), 'utf8');

  const mdPath = path.join(ROOT_DIR, `note-${noteNum}.md`);
  fs.writeFileSync(mdPath, noteMarkdown, 'utf8');

  const plainLen = postData.review.replace(/<[^>]+>/g, '').replace(/\s+/g, '').length;
  console.log(`[note-${noteNum} -> ${slug}] JSON plain text: ${plainLen} chars | MD: ${noteMarkdown.length} chars`);
}

