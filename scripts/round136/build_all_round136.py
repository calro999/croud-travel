def clean_text(text):
    if not text:
        return ""
    # HTMLタグを除去
    text = re.sub(r'<[^>]*>', '', text)
    # 改行やタブをスペースに
    text = re.sub(r'[\r\n\t]+', ' ', text)
    # JSXおよびJSONで問題を起こす文字をサニタイズ
    text = text.replace('{', '（').replace('}', '）').replace('<', '＜').replace('>', '＞').replace('"', '”').replace("'", "’")
    return text.strip()

