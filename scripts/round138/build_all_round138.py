def clean_text(s):
    if not s:
        return ""
    # HTMLタグの除去
    s = re.sub(r'<[^>]+>', '', s)
    # 楽天クチコミの日時メタデータ等の除去
    s = re.sub(r'\d{4}-\d{2}-\d{2}\s+\d{2}:\d{2}:\d{2}投稿', '', s)
    s = re.sub(r'\[つづきを読む\]', '', s)
    # 不適切な単語の除去・置換
    s = re.sub(r'入れ墨.*?ヤクザ', '', s)
    s = re.sub(r'[\r\n\t]+', ' ', s)
    s = re.sub(r'\s+', ' ', s)
    return s.strip()

