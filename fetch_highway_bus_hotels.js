async function main() {
  console.log('楽天APIからホテル情報を取得中...');
  const seasonalHotelsPath = path.join(__dirname, 'src', 'data', 'all_seasonal_rakuten_hotels.json');
  let seasonalHotels = {};
  if (fs.existsSync(seasonalHotelsPath)) {
    seasonalHotels = JSON.parse(fs.readFileSync(seasonalHotelsPath, 'utf8'));
  }

  for (const article of highwayBusArticles) {
    console.log(`取得中: ${article.slug} (${article.hotelKeyword})`);
    try {
      const hotels = await searchRakutenHotels(article.hotelKeyword, 6);
      seasonalHotels[article.slug] = {
        hotels: hotels
      };
      console.log(` -> 成功: ${hotels.length}件のホテルを取得`);
    } catch (e) {
      console.error(` -> 失敗: ${article.slug}`, e.message);
    }
    await new Promise(r => setTimeout(r, 600));
  }

  fs.writeFileSync(seasonalHotelsPath, JSON.stringify(seasonalHotels, null, 2), 'utf8');
  console.log('all_seasonal_rakuten_hotels.json に保存完了');

  fs.writeFileSync(
    path.join(__dirname, 'src', 'data', 'highway_bus_articles_config.json'),
    JSON.stringify(highwayBusArticles, null, 2),
    'utf8'
  );
  console.log('highway_bus_articles_config.json に保存完了');
}

main();
