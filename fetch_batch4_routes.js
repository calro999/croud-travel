async function main() {
  console.log('=== 楽天トラベルAPI第4弾直接リクエスト開始 ===');
  const seasonalHotelsPath = path.join(__dirname, 'src', 'data', 'all_seasonal_rakuten_hotels.json');
  let seasonalHotels = {};
  if (fs.existsSync(seasonalHotelsPath)) {
    seasonalHotels = JSON.parse(fs.readFileSync(seasonalHotelsPath, 'utf8'));
  }

  const existingConfigPath = path.join(__dirname, 'src', 'data', 'highway_bus_articles_config.json');
  let allArticles = [];
  if (fs.existsSync(existingConfigPath)) {
    allArticles = JSON.parse(fs.readFileSync(existingConfigPath, 'utf8'));
  }

  for (const route of additionalBatch4Routes) {
    console.log(`[楽天API直接呼出] キーワード: "${route.hotelKeyword}" (${route.slug})`);
    try {
      const hotels = await searchRakutenHotels(route.hotelKeyword, 6);
      console.log(` -> 取得成功: ${hotels.length} 件`);
      seasonalHotels[route.slug] = {
        hotels: hotels
      };

      const idx = allArticles.findIndex(a => a.slug === route.slug);
      if (idx >= 0) {
        allArticles[idx] = route;
      } else {
        allArticles.push(route);
      }
    } catch (e) {
      console.error(` -> 取得エラー: ${route.slug}`, e.message);
    }
    // レートリミット回避ウェイト
    await new Promise(r => setTimeout(r, 1200));
  }

  fs.writeFileSync(seasonalHotelsPath, JSON.stringify(seasonalHotels, null, 2), 'utf8');
  console.log('src/data/all_seasonal_rakuten_hotels.json を更新しました。');

  fs.writeFileSync(existingConfigPath, JSON.stringify(allArticles, null, 2), 'utf8');
  console.log('src/data/highway_bus_articles_config.json を更新しました。');
}

main();
